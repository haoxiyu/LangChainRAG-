def take(n: int) -> list[str]:
    """取前 n 条(不足则循环补齐),供不同并发档位复用同一批语料。

    循环补齐时会给重复项加上序号后缀 —— 必须让文本真正不同,否则会命中
    embedding 缓存,那一条就测不到向量化环节了。
    """
    if n <= len(QUESTIONS):
        return QUESTIONS[:n]
    out = list(QUESTIONS)
    i = 0
    while len(out) < n:
        out.append(f"{QUESTIONS[i % len(QUESTIONS)]}(第{len(out) // len(QUESTIONS) + 1}次问)")
        i += 1
    return out
